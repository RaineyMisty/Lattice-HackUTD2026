import { useEffect, useState } from 'react';
import { Activity, ArrowRight, Bell, GitBranch, Play, RotateCcw, ShieldAlert } from 'lucide-react';
import { DbConnection, tables } from '../../db/client';
import type { RiskStatus, WorldSnapshot } from '../../shared/types';

const statusLabels: Record<RiskStatus, string> = {
  unknown: 'Awaiting evidence', possible: 'Investigating', direct: 'Direct impact',
  downstream: 'Potential downstream impact', unaffected: 'Unaffected',
};
const positions: Record<string, [number, number]> = {
  tokengate: [350, 43], auth: [230, 145], reporting: [530, 145],
  checkout: [112, 255], merchant: [358, 255],
};
const uri = import.meta.env.VITE_LATTICE_DB_URL || 'http://127.0.0.1:3000';
const database = import.meta.env.VITE_LATTICE_DATABASE || 'lattice-demo';
const tokenKey = `lattice.operator:${uri}:${database}`;
const suppliedToken = new URLSearchParams(window.location.hash.slice(1)).get('operator');
if (suppliedToken) {
  sessionStorage.setItem(tokenKey, suppliedToken);
  history.replaceState(null, '', location.pathname + location.search);
}

export default function App() {
  const [world, setWorld] = useState<WorldSnapshot | null>(null);
  const [connection, setConnection] = useState<DbConnection | null>(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const token = sessionStorage.getItem(tokenKey);
    if (!token) {
      setError('Open the operator link generated by setup.');
      return;
    }

    let disposed = false;
    const fail = (message: string) => {
      if (disposed) return;
      setConnection(null);
      setError(message);
    };
    const conn = DbConnection.builder().withUri(uri).withDatabaseName(database).withToken(token)
      .onConnect(client => {
        if (disposed) return;
        const read = () => {
          if (disposed) return;
          const [snapshot] = client.db.dashboardWorld.iter();
          if (!snapshot) {
            fail('This identity is not registered as an incident operator.');
            return;
          }
          setWorld(JSON.parse(snapshot.snapshotJson) as WorldSnapshot);
          setConnection(client);
        };
        const changed = () => queueMicrotask(read);
        client.db.dashboardWorld.onInsert(changed);
        client.db.dashboardWorld.onUpdate(changed);
        client.db.dashboardWorld.onDelete(changed);
        client.subscriptionBuilder().onApplied(read)
          .onError(() => fail('Unable to subscribe to the incident.'))
          .subscribe(tables.dashboardWorld);
      })
      .onConnectError((_ctx, cause) => fail(cause.message))
      .onDisconnect(() => fail('Disconnected from SpacetimeDB. Reload to reconnect.'))
      .build();

    return () => {
      disposed = true;
      conn.disconnect();
    };
  }, []);

  async function control(action: 'start' | 'reset') {
    if (!connection || busy) return;
    setBusy(true);
    setError('');
    try {
      if (action === 'start') await connection.reducers.injectIncident({});
      else await connection.reducers.resetDemo({});
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : String(cause));
    } finally {
      setBusy(false);
    }
  }

  const phase = !world?.incident ? 'Ready to investigate'
    : world.notifications.length ? 'Departments notified'
    : world.assets.some(asset => asset.status === 'direct') ? 'Impact confirmed'
    : 'Agents investigating';

  return (
    <main className="command">
      <header className="incident">
        <div>
          <div className="kicker"><ShieldAlert size={17} /> LATTICE / ASTER COMMERCE</div>
          <h1>{world?.incident?.title ?? 'TokenGate incident response'}</h1>
          <p>{world?.incident ? `${world.incident.id} · ${world.incident.severity.toUpperCase()}` : 'Fictional vulnerability exercise'} <span className="phase">{phase}</span></p>
        </div>
        <div className="controls">
          <button onClick={() => void control('reset')} disabled={!connection || !world?.incident || busy}><RotateCcw size={16} /> Reset</button>
          <button className="primary" onClick={() => void control('start')} disabled={!connection || !!world?.incident || busy}><Play size={16} /> Start Investigation</button>
        </div>
      </header>
      {error && <p className="error" role="alert">{error}</p>}
      <section className="panel monitor" aria-label="Agent activity">
        <h2><Activity size={18} /> Four-Agent activity</h2>
        <div className="workers">
          {world?.agents.map(agent => (
            <article key={agent.id}>
              <div className="agent-id">AGENT {agent.id} <span className={`state ${agent.status}`}>{agent.status}</span></div>
              <h3>{agent.role}</h3>
              <p>{agent.message}</p>
            </article>
          ))}
          {!world && <p className="muted">Waiting for database state.</p>}
        </div>
      </section>
      <div className="detail">
        <section className="panel graph">
          <h2><GitBranch size={18} /> Dependency and impact</h2>
          <svg viewBox="0 0 700 316" role="img" aria-label="Live service dependency graph">
            <defs><marker id="dependency-arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 Z" fill="#7e8baa" /></marker></defs>
            {world?.dependencies.map(edge => {
              const from = positions[edge.from];
              const to = positions[edge.to];
              if (!from || !to) return null;
              return <line key={`${edge.from}:${edge.to}`} x1={from[0]} y1={from[1] - 32} x2={to[0]} y2={to[1] + 38} markerEnd="url(#dependency-arrow)" />;
            })}
            {world?.incident && <g transform="translate(350 43)" className="node component"><rect x="-80" y="-25" width="160" height="50" rx="9" /><text textAnchor="middle" y="5">TokenGate</text></g>}
            {world?.assets.map(asset => {
              const position = positions[asset.id];
              if (!position) return null;
              return (
                <g key={asset.id} transform={`translate(${position.join(' ')})`} className={`node ${asset.status}`}>
                  <title>{asset.reason}</title>
                  <rect x="-104" y="-34" width="208" height="68" rx="9" />
                  <text className="node-title" textAnchor="middle" y="-5">{asset.name}</text>
                  <text className="node-status" textAnchor="middle" y="17">{statusLabels[asset.status]}</text>
                </g>
              );
            })}
          </svg>
        </section>
        <section className="panel inbox">
          <h2><Bell size={18} /> Department response inbox <span className="count">{world?.notifications.length ?? 0}</span></h2>
          {!world?.notifications.length && <p className="muted">Remediation tasks will appear here as evidence is confirmed.</p>}
          {world?.notifications.map(notification => {
            const task = world.tasks.find(item => item.id === notification.taskId);
            if (!task) return null;
            return (
              <article key={notification.id} className="task">
                <div><span className={`priority ${task.priority}`}>{task.priority}</span> {notification.department}</div>
                <h3>{task.assetName} <ArrowRight size={14} /> {task.owner}</h3>
                <p>{task.instruction}</p>
              </article>
            );
          })}
        </section>
      </div>
    </main>
  );
}
